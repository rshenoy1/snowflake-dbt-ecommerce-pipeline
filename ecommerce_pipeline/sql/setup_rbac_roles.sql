USE ROLE ACCOUNTADMIN;

-- 1. Create a dedicated production role for dbt
CREATE ROLE IF NOT EXISTS TRANSFORMER_ROLE;

-- 2. Allow TRANSFORMER_ROLE to use the TRANSFORM_WH compute warehouse
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER_ROLE;

-- 3. Allow TRANSFORMER_ROLE to READ raw data (SELECT only, no deleting!)
GRANT USAGE ON DATABASE RAW_DATA TO ROLE TRANSFORMER_ROLE;
GRANT USAGE ON SCHEMA RAW_DATA.ECOMMERCE TO ROLE TRANSFORMER_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RAW_DATA.ECOMMERCE TO ROLE TRANSFORMER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW_DATA.ECOMMERCE TO ROLE TRANSFORMER_ROLE;

-- 4. Allow TRANSFORMER_ROLE to BUILD views & tables in ANALYTICS
GRANT USAGE, CREATE SCHEMA ON DATABASE ANALYTICS TO ROLE TRANSFORMER_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA ANALYTICS.DBT_DEV TO ROLE TRANSFORMER_ROLE;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA ANALYTICS.DBT_DEV TO ROLE TRANSFORMER_ROLE;
GRANT ALL PRIVILEGES ON ALL VIEWS IN SCHEMA ANALYTICS.DBT_DEV TO ROLE TRANSFORMER_ROLE;

-- 5. Assign TRANSFORMER_ROLE to DBT_USER
GRANT ROLE TRANSFORMER_ROLE TO USER DBT_USER;
ALTER USER DBT_USER SET DEFAULT_ROLE = TRANSFORMER_ROLE;