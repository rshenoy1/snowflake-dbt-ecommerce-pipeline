USE ROLE ACCOUNTADMIN;
USE WAREHOUSE TRANSFORM_WH;

-- ============================================================================
-- LEVEL 3 - MODULE 4: SNOWFLAKE TASK DAG (PARENT -> CHILD ORCHESTRATION)
-- ============================================================================

-- 1. Create the history table that the Child Task populates
CREATE OR REPLACE TABLE ANALYTICS.DBT_DEV.CDC_RUN_HISTORY (
    run_timestamp TIMESTAMP_NTZ,
    total_cdc_rows INT
);

-- 2. ROOT (PARENT) TASK: Runs every 1 minute ONLY if the Stream has new rows
CREATE OR REPLACE TASK ANALYTICS.DBT_DEV.TASK_1_INGEST_CDC
  WAREHOUSE = TRANSFORM_WH
  SCHEDULE = '1 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('RAW_DATA.ECOMMERCE.RAW_ORDERS_STREAM')
AS
INSERT INTO ANALYTICS.DBT_DEV.CDC_ORDERS_LOG
SELECT
    raw_json:order_id::INT,
    raw_json:customer_id::INT,
    raw_json:amount::FLOAT,
    raw_json:status::STRING,
    METADATA$ACTION,
    CURRENT_TIMESTAMP()
FROM RAW_DATA.ECOMMERCE.RAW_ORDERS_STREAM;

-- 3. CHILD TASK: No schedule! Waits for TASK_1 to succeed using 'AFTER'
CREATE OR REPLACE TASK ANALYTICS.DBT_DEV.TASK_2_UPDATE_AUDIT_STATS
  WAREHOUSE = TRANSFORM_WH
  AFTER ANALYTICS.DBT_DEV.TASK_1_INGEST_CDC
AS
INSERT INTO ANALYTICS.DBT_DEV.CDC_RUN_HISTORY
SELECT CURRENT_TIMESTAMP(), COUNT(*)
FROM ANALYTICS.DBT_DEV.CDC_ORDERS_LOG;

-- 4. Simulate Order #202 arriving in RAW_ORDERS so the Stream has data waiting
INSERT INTO RAW_DATA.ECOMMERCE.RAW_ORDERS (raw_json, loaded_at)
SELECT PARSE_JSON('{"order_id": 202, "customer_id": 2, "amount": 500.00, "status": "completed"}'), CURRENT_TIMESTAMP();

-- 5. STARTUP (Bottom-Up): Resume Child Task FIRST, Root Task LAST
ALTER TASK ANALYTICS.DBT_DEV.TASK_2_UPDATE_AUDIT_STATS RESUME;
ALTER TASK ANALYTICS.DBT_DEV.TASK_1_INGEST_CDC RESUME;

-- (Wait ~65 seconds for the 1-minute schedule to fire)

-- 6. VERIFY RESULTS
SELECT * FROM ANALYTICS.DBT_DEV.CDC_ORDERS_LOG;
SELECT * FROM ANALYTICS.DBT_DEV.CDC_RUN_HISTORY;

-- 7. SHUTDOWN (Top-Down): Suspend Root Task FIRST, Child Task LAST
ALTER TASK ANALYTICS.DBT_DEV.TASK_1_INGEST_CDC SUSPEND;
ALTER TASK ANALYTICS.DBT_DEV.TASK_2_UPDATE_AUDIT_STATS SUSPEND;